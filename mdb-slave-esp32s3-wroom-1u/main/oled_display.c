/*
 * VMflow.xyz
 *
 * oled_display.c — SSD1306 128x64 I2C OLED text driver
 *
 * Vendored rather than pulled in via a graphics library (u8g2/lvgl): this
 * board only ever needs 8 fixed text rows, which line up exactly with the
 * SSD1306's 8 hardware pages, so a full font/graphics stack would be a lot
 * of flash and a component-registry dependency for something a ~150-line
 * page-per-row driver already covers.
 *
 * I2C bring-up mirrors modem.c's AXP2101 PMU driver (same i2c_master API,
 * same bus-then-device pattern) but on its own port/pins so OLED traffic
 * never shares a bus with PMU traffic.
 */

